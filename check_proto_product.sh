set -euo pipefail

SCRIPTS_DIR="$( cd -P "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "${SCRIPTS_DIR}"

# Include staged and untracked products, as well as generated type stubs.
# Git pathspecs avoid platform-specific grep behavior and human status output.
changes="$(git status --porcelain --untracked-files=all -- \
  ':(glob)pymilvus/grpc_gen/*_pb2.py' \
  ':(glob)pymilvus/grpc_gen/*_pb2_grpc.py' \
  ':(glob)pymilvus/grpc_gen/*_pb2.pyi')"

if [[ -n "${changes}" ]]; then
  echo "The milvus-proto commit doesn't match with files generated by proto!"
  printf '%s\n' "${changes}"
  exit 1
fi

echo "Success to check the proto files"
